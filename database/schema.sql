-- Path-based PostgreSQL schema with grouped F1-F4 normalization for the 163D Flower CBIR system.

CREATE TABLE IF NOT EXISTS public.flower_images (
    image_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename VARCHAR(255) NOT NULL UNIQUE,
    image_path TEXT NOT NULL,
    mask_path TEXT NOT NULL,
    width INTEGER NOT NULL CHECK (width = 384),
    height INTEGER NOT NULL CHECK (height = 384),
    image_format VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.flower_features (
    feature_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id INTEGER NOT NULL UNIQUE REFERENCES public.flower_images(image_id) ON DELETE CASCADE,
    hs_histogram DOUBLE PRECISION[] NOT NULL CHECK (cardinality(hs_histogram) = 72),
    v_histogram DOUBLE PRECISION[] NOT NULL CHECK (cardinality(v_histogram) = 6),
    lab_mean DOUBLE PRECISION[] NOT NULL CHECK (cardinality(lab_mean) = 9),
    lab_std DOUBLE PRECISION[] NOT NULL CHECK (cardinality(lab_std) = 9),
    lbp_histogram DOUBLE PRECISION[] NOT NULL CHECK (cardinality(lbp_histogram) = 28),
    circularity DOUBLE PRECISION NOT NULL,
    solidity DOUBLE PRECISION NOT NULL,
    aspect_ratio DOUBLE PRECISION NOT NULL,
    rotated_extent DOUBLE PRECISION NOT NULL,
    radial_spectrum DOUBLE PRECISION[] NOT NULL CHECK (cardinality(radial_spectrum) = 12),
    iap DOUBLE PRECISION[] NOT NULL CHECK (cardinality(iap) = 16),
    iep DOUBLE PRECISION[] NOT NULL CHECK (cardinality(iep) = 7),
    extracted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.feature_normalization (
    normalization_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method VARCHAR(64) NOT NULL,
    f1_means DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f1_means) = 78),
    f1_stds DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f1_stds) = 78),
    f2_means DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f2_means) = 18),
    f2_stds DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f2_stds) = 18),
    f3_means DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f3_means) = 28),
    f3_stds DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f3_stds) = 28),
    f4_means DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f4_means) = 39),
    f4_stds DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f4_stds) = 39),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.normalized_features (
    normalized_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id INTEGER NOT NULL UNIQUE REFERENCES public.flower_images(image_id) ON DELETE CASCADE,
    normalization_id INTEGER NOT NULL REFERENCES public.feature_normalization(normalization_id),
    f1_vector DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f1_vector) = 78),
    f2_vector DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f2_vector) = 18),
    f3_vector DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f3_vector) = 28),
    f4_vector DOUBLE PRECISION[] NOT NULL CHECK (cardinality(f4_vector) = 39),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.cbir_index_versions (
    version_id TEXT PRIMARY KEY,
    normalization_id INTEGER NOT NULL UNIQUE REFERENCES public.feature_normalization(normalization_id),
    contract JSONB NOT NULL,
    manifest JSONB NOT NULL,
    normalizer JSONB NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS cbir_one_active_index
    ON public.cbir_index_versions ((active)) WHERE active;

CREATE TABLE IF NOT EXISTS public.cbir_index_entries (
    version_id TEXT NOT NULL REFERENCES public.cbir_index_versions(version_id),
    image_id INTEGER NOT NULL REFERENCES public.flower_images(image_id),
    raw_vector DOUBLE PRECISION[] NOT NULL CHECK (array_length(raw_vector, 1) = 163),
    normalized_vector DOUBLE PRECISION[] NOT NULL CHECK (array_length(normalized_vector, 1) = 163),
    metadata JSONB NOT NULL,
    PRIMARY KEY (version_id, image_id)
);

CREATE TABLE IF NOT EXISTS public.retrieval_history (
    query_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_image_path TEXT NOT NULL,
    query_features DOUBLE PRECISION[] NOT NULL,
    top5_results JSONB NOT NULL,
    execution_ms DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    index_version TEXT,
    weights DOUBLE PRECISION[],
    query_context JSONB
);

CREATE OR REPLACE VIEW public.flower_dataset AS
SELECT
    i.image_id, i.filename, i.image_path, i.mask_path, i.width, i.height, i.image_format,
    f.feature_id, f.hs_histogram, f.v_histogram, f.lab_mean, f.lab_std, f.lbp_histogram,
    f.circularity, f.solidity, f.aspect_ratio, f.rotated_extent,
    f.radial_spectrum, f.iap, f.iep, f.extracted_at
FROM public.flower_images i
JOIN public.flower_features f ON f.image_id = i.image_id;
